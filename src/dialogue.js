// Реплики по зонам касания и уровню симпатии.
// tier: 0 — незнакомцы, 1 — друзья, 2 — близкие.
// expression — пресет VRM (happy, angry, sad, relaxed, surprised).
// affection — сколько симпатии даёт/отнимает касание.

export const TIERS = [
  { min: 0, label: 'Незнакомец' },
  { min: 30, label: 'Друг' },
  { min: 70, label: 'Близкий человек' },
];

export function tierFor(affection) {
  let t = 0;
  TIERS.forEach((tier, i) => { if (affection >= tier.min) t = i; });
  return t;
}

